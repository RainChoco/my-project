async function seedDemoContracts({ ContractModel }) {
    if (!ContractModel) {
        throw new Error('ContractModel is required');
    }

    for (const contractData of DEMO_CONTRACTS) {
        const existing = await ContractModel.findByPk(contractData.id);
        if (!existing) {
            await ContractModel.create(contractData);
        } else {
            await existing.update(contractData);
        }
    }
}

async function seedDemoTenders({ TenderModel }) {
    if (!TenderModel) {
        throw new Error('TenderModel is required');
    }

    for (const tenderData of DEMO_TENDERS) {
        const existing = await TenderModel.findOne({ where: { tender_ref_no: tenderData.tender_ref_no } });
        if (!existing) {
            await TenderModel.create(tenderData);
        } else {
            await existing.update(tenderData);
        }
    }
}

async function seedDemoData({ ContractModel, TenderModel }) {
    await seedDemoContracts({ ContractModel });
    await seedDemoTenders({ TenderModel });
}

module.exports = {
    seedDemoContracts,
    seedDemoTenders,
    seedDemoData,
};
